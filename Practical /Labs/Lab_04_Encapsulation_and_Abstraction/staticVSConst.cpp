/*
• const: تجعل المتغير للقراءة فقط (ثابت لا يتغير) بعد إعطائه قيمة، وتمنع تعديله بالخطأ.
• static: تحافظ على بقاء المتغير في الذاكرة طوال فترة البرنامج، أو تجعله مشتركاً بين جميع الكائنات دون الحاجة لنسخ متعددة.
• static const: تدمج الميزتين معاً؛ قيمة ثابتة لا تتغير وفي نفس الوقت نسخة واحدة مشتركة في الذاكرة.
*/
#include <iostream>
void counterFunction() {
    const int x  = 5;      // ثابتة لا تتغير، وتُعاد تهيئتها في كل استدعاء
    static int y = 0;     // نسخة واحدة في الذاكرة، تحتفظ بقيمتها السابقة

    // x = 10;            // خطأ برميجي! لا يمكن تعديل const
    y++;                  // مسموح، لأن static يمكن تعديل قيمته

    std::cout << "const x = " << x << " | static y = " << y << "\n";
}
int main() {
    counterFunction();    // ستطبع: const x = 5 | static y = 1
    counterFunction();    // ستطبع: const x = 5 | static y = 2
    return 0;
}
